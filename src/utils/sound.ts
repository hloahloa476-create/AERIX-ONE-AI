// Ambient Synthesizer Node for the Music App
class ProceduralSynthesizer {
  private ctx: AudioContext | null = null;
  private isPlaying = false;
  private intervalId: number | null = null;
  private currentFreqs: number[] = [220, 277, 330, 440];

  start(frequencies: number[] = [220, 277, 330, 440]) {
    this.ctx = getAudioContext();
    if (!this.ctx) return;
    this.currentFreqs = frequencies;
    this.isPlaying = true;

    // Trigger chords periodically
    let step = 0;
    this.triggerNote(this.currentFreqs[0]);
    this.intervalId = window.setInterval(() => {
      if (!this.isPlaying || !this.ctx) return;
      step = (step + 1) % this.currentFreqs.length;
      this.triggerNote(this.currentFreqs[step]);
    }, 750);
  }

  triggerNote(freq: number) {
    if (!this.ctx) return;
    try {
      const now = this.ctx.currentTime;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();
      const filter = this.ctx.createBiquadFilter();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(freq, now);

      filter.type = 'lowpass';
      filter.frequency.setValueAtTime(800, now);

      gain.gain.setValueAtTime(0.001, now);
      gain.gain.linearRampToValueAtTime(0.15, now + 0.2);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 1.2);

      osc.connect(filter);
      filter.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start(now);
      osc.stop(now + 1.2);
    } catch {
      // Audio error
    }
  }

  stop() {
    this.isPlaying = false;
    if (this.intervalId) {
      clearInterval(this.intervalId);
      this.intervalId = null;
    }
  }

  setFrequencies(freqs: number[]) {
    this.currentFreqs = freqs;
  }
}

export const musicSynth = new ProceduralSynthesizer();
